const { search } = await import('./precision-sb-clamp.generated.mjs');

const R = new Report();
const KEYS = ['friends', 'progress', 'freeDays', 'compact', 'timeWindow', 'examSpread'];
function runInstance(inst) {
  const stack = [], viol = [];
  let nodes = 0, minSlack = Infinity;
  globalThis.__searchHook = {
    enter(i, bound, terms, selDesc) { const f = { i, bound, terms: { ...terms }, sel: selDesc, best: -Infinity, bestM: {} }; stack.push(f); nodes++; return f; },
    leaf(score, m, weights) { const f = stack[stack.length - 1]; if (score > f.best) f.best = score; for (const k of KEYS) f.bestM[k] = Math.max(f.bestM[k] ?? -Infinity, (weights[k] ?? 0) * (m[k] ?? 0)); },
    exit(f) {
      stack.pop();
      const slack = f.bound - f.best;
      if (f.best > -Infinity) {
        minSlack = Math.min(minSlack, slack);
        if (f.bound < f.best) viol.push({ i: f.i, bound: f.bound, best: f.best, sel: f.sel, badTerms: KEYS.filter((k) => f.terms[k] + 1e-12 < f.bestM[k]).map((k) => `${k}: bound-term ${f.terms[k]} < best-leaf-term ${f.bestM[k]}`) });
      }
      const p = stack[stack.length - 1];
      if (p) { if (f.best > p.best) p.best = f.best; for (const k of KEYS) p.bestM[k] = Math.max(p.bestM[k] ?? -Infinity, f.bestM[k] ?? -Infinity); }
    },
  };
  try { search({ ...inst, topK: 1e9, timeLimitMs: 1e9, prune: false }); } finally { globalThis.__searchHook = null; }
  return { nodes, viol, minSlack };
}

function sweep(label, mk, n) {
  let totalNodes = 0, bad = 0, first = null, badTerms = {};
  for (let seed = 1; seed <= n; seed++) {
    const inst = mk(mulberry32(seed * 104729));
    const r = runInstance(inst);
    totalNodes += r.nodes;
    if (r.viol.length) { bad++; first ??= { seed, nodes: r.nodes, v: r.viol[0] }; for (const v of r.viol) for (const t of v.badTerms) badTerms[t.split(':')[0]] = (badTerms[t.split(':')[0]] ?? 0) + 1; }
  }
  return { label, n, totalNodes, bad, first, badTerms };
}
const noFriendsNoBias = (rng) => { const i = genInstance(rng, { parallelRate: 0, pinRate: 0 }); i.friends = []; i.bias = {}; return i; };
const withFriends = (rng) => { const i = genInstance(rng, { parallelRate: 0, pinRate: 0 }); i.bias = {}; i.friends = i.friends.length ? i.friends : [{ name: 'F', groups: Object.values(i.data.courses).flatMap((c) => c.groups.map((g) => g.id)).filter((_, k) => k % 3 === 0), weight: 2, active: true }]; i.weights = { ...i.weights, friends: 5 }; return i; };
const withBias = (rng) => { const i = genInstance(rng, { parallelRate: 0, pinRate: 0 }); i.friends = []; if (!Object.keys(i.bias).length) for (const id of Object.keys(i.data.courses)) i.bias[id] = -Math.floor(i.data.courses[id].credits); return i; };
const examsOnly = (rng) => { const i = genInstance(rng, { examsPublished: true, parallelRate: 0, pinRate: 0 }); i.friends = []; i.bias = {}; i.constraints.examsSameDay = 'allow'; i.weights = { ...i.weights, examSpread: 5 }; return i; };
const all = [
  sweep('no friends, no bias, exams random', noFriendsNoBias, 400),
  sweep('exams published, same-day allowed, examSpread=5', examsOnly, 300),
  sweep('with friends (friends weight 5)', withFriends, 400),
  sweep('bias <= 0 (searchYear style: -credits for a late-semester load)', withBias, 400),
];
for (const s of all) R.info(`${s.label}: instances=${s.n} nodes=${s.totalNodes} instances-with-violation=${s.bad} offending terms=${JSON.stringify(s.badTerms)}`);
R.check('SB-1 bound() is admissible when there are no friends and no bias (all nodes, random instances)', all[0].bad === 0 && all[1].bad === 0, `violations: ${all[0].bad}+${all[1].bad}`);
