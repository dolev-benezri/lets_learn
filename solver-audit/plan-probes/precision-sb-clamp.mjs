// search-bound-admissible.mjs
// WHAT: checks that the private bound() of search() is an optimistic (admissible) bound: at EVERY node of the DFS,
//       bound(i, mask, val) must be >= the best score of any valid leaf below that node. If it is smaller, branch-and-bound
//       can cut a subtree that holds a better plan and search() returns a worse top-K than the exhaustive search.
// HOW:  bound() is a private closure variable, so this script makes an instrumented COPY of web/solver-core.js at run time
//       (solver-audit/repro/precision-sb-clamp.generated.mjs, rewritten on every run; the original is never touched).
//       The copy differs only by: the rules.js import path, a wrapper around dfs() that records bound() at entry and the best
//       leaf score below on exit, a per-term breakdown of bound(), and a hook after the leaf score is computed.
//       All text patches are asserted to apply exactly once, so the script fails loudly if the source changes.
// TARGETS: web/solver-core.js:308-322 (bound), 285-307 (restValue / restShared / friendsUp), 344-360 (dfs), 327-342 (leaf).
// RUN:   node solver-audit/repro/search-bound-admissible.mjs      (~5-20 s)
// OUTPUT: CHECK SB-1 = bound admissible on all nodes of N random instances w/o friends;  BUG SB-2.. = violations found, with the
//         violating term, a minimal instance seed and the lost plan (see findings: search-1).
