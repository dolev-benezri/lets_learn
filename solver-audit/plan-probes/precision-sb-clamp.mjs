const mal = sweep('MALFORMED data (end < start), friends', (rng) => { const i = genInstance(rng, { parallelRate: 0, pinRate: 0, malformed: true }); i.bias = {}; i.friends = i.friends.length ? i.friends : [{ name: 'F', groups: Object.values(i.data.courses).flatMap((c) => c.groups.map((g) => g.id)).filter((_, k) => k % 3 === 0), weight: 2, active: true }]; i.weights = { ...i.weights, friends: 5 }; return i; }, 400);
