// year-instrument.mjs - builds an INSTRUMENTED COPY of web/solver-core.js inside solver-audit/repro/ (the repo file is never touched).
// The copy is regenerated from the current source on every call; each patch must match exactly once, so source drift is detected.
// Knobs (read at call time from globalThis):
//   __YEAR_A_TOP    replaces the constant A_TOP = 50 (web/solver-core.js:376, used at :420)   -> e.g. 1e9 = no top-50 cut
//   __YEAR_NO_SEEDS 1 = skip the per-must seed searches (web/solver-core.js:430-438)
//   __YEAR_NO_RELAX 1 = skip the relax rounds (web/solver-core.js:455-479): a B without a full plan stays b = null
//   __YEAR_FIX_SEEDS 1 = the seed loop ignores outside-program (id:null) prerequisites, as classify() does (web/rules.js:67)
//   __YEAR_CAPTURE  object: receives { aList } = the A alternatives actually tried (web/solver-core.js:440-441)
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';

const HERE = new URL('./', import.meta.url);
function patch(src, from, to) {
  const n = src.split(from).length - 1;
  if (n !== 1) throw new Error(`instrument: expected exactly 1 match for ${JSON.stringify(from)}, found ${n} (solver-core.js changed?)`);
  return src.replace(from, to);
}
export async function loadInstrumented() {
  let src = fs.readFileSync(new URL('../../web/solver-core.js', import.meta.url), 'utf8');
  src = patch(src, "from './rules.js'", "from '../../web/rules.js'");
  src = patch(src, 'topK: A_TOP, distinct: true, timeLimitMs: timeLimitMs * A_SHARE', 'topK: globalThis.__YEAR_A_TOP ?? A_TOP, distinct: true, timeLimitMs: timeLimitMs * A_SHARE');
  src = patch(src, 'for (const m of must) {', 'for (const m of (globalThis.__YEAR_NO_SEEDS ? [] : must)) {');
  src = patch(src, 'for (const [i, a] of aList.entries()) {', 'if (globalThis.__YEAR_CAPTURE) globalThis.__YEAR_CAPTURE.aList = aList;\n  for (const [i, a] of aList.entries()) {');
  src = patch(src, 'if (!rb.results.length) {', 'if (!rb.results.length && !globalThis.__YEAR_NO_RELAX) {');
  // 2026-10-07 (stage 5, issue #5): the seed loop skips all-outside prerequisites itself, so __YEAR_FIX_SEEDS has nothing left to patch.
  const out = new URL('year-core.instrumented.generated.mjs', HERE);
  fs.writeFileSync(out, `// GENERATED by year-instrument.mjs from web/solver-core.js - do not edit, do not commit.\n${src}`);
  return import(pathToFileURL(fileURLToPath(out)).href + `?t=${Date.now()}`);
}
import { fileURLToPath } from 'node:url';
